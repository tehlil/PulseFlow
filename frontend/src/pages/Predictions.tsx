import { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import { api } from '../services/api';
import { Sparkles, CheckCircle } from 'lucide-react';
import { BarChart, Bar, XAxis, YAxis, Tooltip, ResponsiveContainer } from 'recharts';

export default function Predictions() {
  const [selectedPrediction, setSelectedPrediction] = useState<any | null>(null);

  const { data, isLoading, error } = useQuery({
    queryKey: ['analyticsOverview'], // Reuses the analytics fetch which includes recent predictions
    queryFn: () => api.get('/analytics/overview').then((res) => res.data),
  });

  if (isLoading) {
    return <div className="p-8 text-center text-primary-muted animate-pulse">Loading AI analysis dashboards...</div>;
  }

  if (error || !data) {
    return (
      <div className="p-6 bg-healthcare-rose/10 border border-healthcare-rose/20 rounded-xl text-healthcare-rose text-sm">
        Failed to load prediction analysis logs.
      </div>
    );
  }

  const { recentPredictions } = data;

  // Set default selection
  const activePred = selectedPrediction || recentPredictions[0];

  // Prep chart data for active prediction
  const chartData = activePred
    ? (activePred.contributingFactors as any[]).map((f) => ({
        name: f.factor,
        weight: f.weight,
      }))
    : [];

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold text-white tracking-tight flex items-center space-x-2">
          <Sparkles className="w-6 h-6 text-healthcare-amber" />
          <span>Explainable AI Risk Engine</span>
        </h1>
        <p className="text-xs text-primary-muted">Exposes the scoring models and contributing indicators generated by prediction workers.</p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        
        {/* Left Side: Predictions list */}
        <div className="bg-background-card border border-border rounded-xl shadow-sm overflow-hidden flex flex-col h-[520px]">
          <div className="p-4 border-b border-border bg-background/25">
            <h2 className="text-xs font-bold text-white uppercase tracking-wider">Predictor Log Runs</h2>
          </div>
          
          <div className="flex-1 overflow-y-auto divide-y divide-border/60">
            {recentPredictions.length === 0 ? (
              <p className="text-xs text-primary-muted text-center py-12">No predictions logged yet.</p>
            ) : (
              recentPredictions.map((pred: any) => {
                const isSelected = activePred?.id === pred.id;
                let textClass = 'text-healthcare-emerald';
                if (pred.riskCategory === 'MODERATE') textClass = 'text-healthcare-amber';
                if (pred.riskCategory === 'HIGH' || pred.riskCategory === 'CRITICAL') textClass = 'text-healthcare-rose';

                return (
                  <button
                    key={pred.id}
                    onClick={() => setSelectedPrediction(pred)}
                    className={`w-full text-left p-4 transition-colors flex flex-col space-y-1 ${
                      isSelected ? 'bg-background-hover' : 'hover:bg-background-hover/30'
                    }`}
                  >
                    <div className="flex justify-between items-baseline">
                      <span className="text-xs font-bold text-white uppercase">{pred.predictionType} Target</span>
                      <span className={`text-[10px] font-bold ${textClass}`}>{pred.riskCategory}</span>
                    </div>
                    <div className="flex justify-between text-xs text-primary-muted">
                      <span>{pred.patient.firstName} {pred.patient.lastName}</span>
                      <span className="font-mono text-[10px]">Score: {pred.riskScore}%</span>
                    </div>
                    <span className="text-[10px] text-primary-muted font-mono pt-1">
                      {new Date(pred.createdAt).toLocaleString(undefined, { dateStyle: 'short', timeStyle: 'short' })}
                    </span>
                  </button>
                );
              })
            )}
          </div>
        </div>

        {/* Right Side: Explainability breakdown details */}
        <div className="lg:col-span-2 space-y-6">
          {activePred ? (
            <>
              {/* EAI Details Card */}
              <div className="bg-background-card border border-border p-6 rounded-xl shadow-sm space-y-6">
                <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between space-y-2 sm:space-y-0 pb-4 border-b border-border">
                  <div>
                    <h2 className="text-sm font-bold text-white uppercase tracking-wider">
                      Model Analysis: {activePred.predictionType}
                    </h2>
                    <p className="text-[10px] text-primary-muted">
                      Evaluated for Patient: {activePred.patient.firstName} {activePred.patient.lastName} (MRN: {activePred.patient.mrn})
                    </p>
                  </div>
                  <span className="text-xs font-mono text-primary-muted">Model: {activePred.modelName}</span>
                </div>

                <div className="grid grid-cols-1 sm:grid-cols-3 gap-6">
                  {/* Score */}
                  <div className="bg-background/40 border border-border/50 p-4 rounded-xl space-y-1 text-center">
                    <p className="text-[9px] text-primary-muted uppercase font-bold">Calculated Risk Score</p>
                    <p className="text-2xl font-extrabold text-white">{activePred.riskScore}%</p>
                  </div>

                  {/* Level */}
                  <div className="bg-background/40 border border-border/50 p-4 rounded-xl space-y-1 text-center">
                    <p className="text-[9px] text-primary-muted uppercase font-bold">Risk Tier</p>
                    <p className={`text-xl font-bold uppercase ${
                      activePred.riskCategory === 'CRITICAL' ? 'text-red-500' :
                      activePred.riskCategory === 'HIGH' ? 'text-healthcare-rose' :
                      activePred.riskCategory === 'MODERATE' ? 'text-healthcare-amber' :
                      'text-healthcare-emerald'
                    }`}>{activePred.riskCategory}</p>
                  </div>

                  {/* Confidence */}
                  <div className="bg-background/40 border border-border/50 p-4 rounded-xl space-y-1 text-center">
                    <p className="text-[9px] text-primary-muted uppercase font-bold">Confidence score</p>
                    <p className="text-2xl font-extrabold text-primary-muted">
                      {Math.round(activePred.confidenceScore * 100)}%
                    </p>
                  </div>
                </div>

                {/* Contributing factors chart */}
                <div className="space-y-3">
                  <h3 className="text-xs font-bold text-white uppercase tracking-wider">Contribution Factor Breakdown</h3>
                  <div className="h-48 w-full bg-background/25 border border-border/40 p-4 rounded-xl">
                    {chartData.length === 0 ? (
                      <div className="h-full flex items-center justify-center text-xs text-primary-muted">
                        No active contributing risk elements found.
                      </div>
                    ) : (
                      <ResponsiveContainer width="100%" height="100%">
                        <BarChart data={chartData} layout="vertical" margin={{ top: 0, right: 10, left: 30, bottom: 0 }}>
                          <XAxis type="number" stroke="#8A8F98" fontSize={9} />
                          <YAxis dataKey="name" type="category" stroke="#8A8F98" fontSize={9} />
                          <Tooltip 
                            contentStyle={{ backgroundColor: '#121215', borderColor: '#1F1F24', borderRadius: 8 }}
                            itemStyle={{ fontSize: 10 }}
                          />
                          <Bar dataKey="weight" fill="#14B8A6" radius={[0, 4, 4, 0]} />
                        </BarChart>
                      </ResponsiveContainer>
                    )}
                  </div>
                </div>

                {/* Recommended actions */}
                <div className="space-y-3 border-t border-border pt-4">
                  <h3 className="text-xs font-bold text-white uppercase tracking-wider flex items-center space-x-1.5">
                    <CheckCircle className="w-4 h-4 text-healthcare-teal" />
                    <span>Suggested Action Directives</span>
                  </h3>
                  <ul className="space-y-1.5 text-xs text-primary-muted list-disc list-inside">
                    {(activePred.recommendedActions as string[]).map((action, i) => (
                      <li key={i} className="leading-relaxed">{action}</li>
                    ))}
                  </ul>
                </div>
              </div>
            </>
          ) : (
            <div className="bg-background-card border border-border p-12 text-center text-primary-muted text-xs rounded-xl shadow-sm">
              Please log clinical checkups to evaluate predictions and examine AI breakdowns.
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
